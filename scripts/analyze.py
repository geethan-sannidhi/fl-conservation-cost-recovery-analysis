import csv, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import eccr  # noqa: E402

progs = eccr.load_programs()
out = ROOT / "outputs"; out.mkdir(exist_ok=True)

# 1. program metrics
rows = []
for p in progs:
    a = eccr.analyzable(p)
    r = {"utility": p["utility"], "program": p["program"], "program_cost_usd": p["cost"],
         "annual_kwh_at_meter": p["kwh"], "demand_program": p["demand_program"],
         "cost_per_kwh_usd": eccr.cost_per_kwh(p["cost"], p["kwh"]) if a else None}
    for v in eccr.AVOIDED_COST_SCENARIOS:
        r[f"payback_years_at_{v:.2f}_per_kwh"] = eccr.payback_years(p["cost"], p["kwh"], v) if a else None
    rows.append(r)
with open(out / "program_metrics.csv", "w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=list(rows[0])); w.writeheader()
    for r in rows:
        w.writerow({k: (round(v, 4) if isinstance(v, float) else v) for k, v in r.items()})

# 2. participation sensitivity
srows = []
for p in progs:
    if not eccr.analyzable(p):
        continue
    for s in eccr.PARTICIPATION_SCENARIOS:
        c, k = eccr.scenario(p["cost"], p["kwh"], s)
        srows.append({"utility": p["utility"], "program": p["program"], "participation_share": s,
                      "cost_usd": round(c), "annual_kwh": round(k), "cost_per_kwh_usd": round(c / k, 4)})
with open(out / "participation_sensitivity.csv", "w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=list(srows[0])); w.writeheader(); w.writerows(srows)

# 3. reconciliation checks
tot = eccr.utility_totals(progs)
goals = {r["utility"]: r for r in csv.DictReader(open(ROOT / "data" / "goals_vs_achieved_2025.csv"))}
ct3 = list(csv.DictReader(open(ROOT / "data" / "fpl_eccr_2025_ct3_costs.csv")))
ct3_sum = sum(int(r["total_cost_2025_usd"]) for r in ct3)
CT2_TOTAL = 168_697_310  # Exhibit LSN-1 p.3, CT-2 line 10 'Total Adjusted Program Costs' (Actual)
lines = ["# Reconciliation checks (generated by scripts/analyze.py)", ""]
lines.append("## Savings: sum of program pages vs. utility-reported total (GWh at generator)")
lines.append("| Utility | Sum of program pages | Reported total | Difference |\n|---|---|---|---|")
for u in ("Florida Power & Light", "Duke Energy Florida", "Tampa Electric"):
    s = tot[u]["kwh_gen"] / 1e6; rep = float(goals[u]["achieved_gwh"])
    lines.append(f"| {u} | {s:.2f} | {rep:.2f} | {s - rep:+.2f} ({(s - rep) / rep:+.1%}) |")
lines += ["", "## FPL cost: ECCR program costs (Exhibit LSN-1 p.27) vs. CT-2 total",
          f"- Sum of 19 program/common lines: ${ct3_sum:,}",
          f"- CT-2 line 10 Total Adjusted Program Costs: ${CT2_TOTAL:,}",
          f"- Difference: ${ct3_sum - CT2_TOTAL:,} (rounding in the filing)", ""]
fpl = {p["program"]: p for p in progs if p["utility"].startswith("Florida Power")}
lines.append("## FPL cost: DSM annual report ($000, rounded) vs. ECCR exhibit ($)")
lines.append("| Program | DSM report | ECCR exhibit | Match within $500 |\n|---|---|---|---|")
alias = {"Residential Load Management (On Call®)": 'Residential Load Management ("On Call")',
         "Residential New Construction (BuildSmart®)": "Residential New Construction (BuildSmart)",
         "Residential Low-Income Renter Pilot": "Residential Low Income Renter Pilot",
         "Business Heating, Ventilating & Air Conditioning": "Business Heating, Ventilating & A/C"}
ct3_by = {r["program"]: int(r["total_cost_2025_usd"]) for r in ct3}
bad = 0
for name, p in fpl.items():
    ex = ct3_by.get(alias.get(name, name))
    if ex is None:
        lines.append(f"| {name} | {p['cost']:,.0f} | (no match) | - |"); bad += 1; continue
    ok = abs(p["cost"] - ex) <= 500
    bad += not ok
    lines.append(f"| {name} | {p['cost']:,.0f} | {ex:,} | {'yes' if ok else 'NO'} |")
lines += ["", "## FPL costs outside the DSM program pages (ECCR recovers these too)"]
dsm_names = {alias.get(n, n) for n in fpl}
extra = [(r["program"], int(r["total_cost_2025_usd"])) for r in ct3 if r["program"] not in dsm_names]
for n, v in extra:
    lines.append(f"- {n}: ${v:,}")
lines.append(f"- Total: ${sum(v for _, v in extra):,} "
             f"({sum(v for _, v in extra) / CT2_TOTAL:.1%} of CT-2 total)")
(out / "checks.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))

# 4. staff-style memo (numbers generated from the data, not typed by hand)
ap = [p for p in progs if eccr.analyzable(p)]
mat = sorted([p for p in ap if p["cost"] >= 100_000], key=lambda p: p["cost"] / p["kwh"])
fmt = lambda p: f"| {p['utility']} | {p['program'].title() if p['program'].isupper() else p['program']} | ${p['cost']:,.0f} | {p['kwh'] / 1e6:,.2f} | ${p['cost'] / p['kwh']:.2f} | {eccr.payback_years(p['cost'], p['kwh'], 0.10):.1f} |"
hdr = "| Utility | Program | 2025 cost | GWh saved (meter, first-year) | $ per kWh | Years at $0.10/kWh |\n|---|---|---|---|---|---|"
a_cost = sum(p["cost"] for p in ap); a_kwh = sum(p["kwh"] for p in ap)
memo = f"""# Memo: Screening of 2025 Conservation Program Cost-Effectiveness (FPL, Duke Energy Florida, Tampa Electric)

*Independent portfolio analysis built from public filings; not an official Commission staff product. Method and limits: docs/METHODOLOGY.md.*

## Purpose
Screen the energy-saving programs three of Florida's four investor-owned electric utilities reported for 2025, using their filed annual DSM reports and FPL's ECCR final true-up exhibit, and identify which programs warrant a closer look.

## Scope of what was analyzed
- {len(progs)} programs reported by three utilities; {len(ap)} are energy-efficiency programs with both cost and credited kWh and are screened below. The rest are demand-response/load-control programs (credited in kW, not kWh) or programs with no savings credited (e.g., FPL Home Energy Survey), which cannot be ranked on cost per kWh.
- The {len(ap)} screened programs cost ${a_cost / 1e6:,.1f} million and credit {a_kwh / 1e6:,.1f} GWh of first-year savings at the meter, an average of ${a_cost / a_kwh:.3f} per kWh.
- Florida Public Utilities is excluded from the program screen (its report is formatted differently); it appears only in the goals comparison.

## Lowest cost per kWh saved (programs costing at least $100,000)
{hdr}
""" + "\n".join(fmt(p) for p in mat[:6]) + f"""

## Highest cost per kWh saved (programs costing at least $100,000)
{hdr}
""" + "\n".join(fmt(p) for p in mat[-6:][::-1]) + """

## Goals comparison (2025, as reported by each utility)
""" + "\n".join(f"- {u}: {r['achieved_gwh']} GWh achieved vs. {r['goal_gwh']} GWh goal ({r['basis']})." for u, r in goals.items()) + f"""

## Observations for follow-up
1. **Ranking is sensitive to what a program's cost includes.** Audit and education programs carry cost but credit little direct savings, so their $/kWh looks poor by construction. They should be judged on what they feed into other programs, which these filings do not show.
2. **Data that does not line up.** Tampa Electric's program pages sum to {tot['Tampa Electric']['kwh_gen'] / 1e6:.1f} GWh at the generator against 65.8 GWh in its summary (a gap of {abs(tot['Tampa Electric']['kwh_gen'] / 1e6 - 65.8):.1f} GWh); the report prints combined and per-plan rows, and the summary basis is not stated. Duke's program pages sum to {tot['Duke Energy Florida']['kwh_gen'] / 1e6:.2f} GWh vs. 65 reported (rounding). FPL's reconcile exactly. See outputs/checks.md.
3. **FPL costs recovered beyond the listed programs.** About ${sum(v for _, v in extra) / 1e6:,.1f} million ({sum(v for _, v in extra) / CT2_TOTAL:.0%} of FPL's 2025 ECCR program costs) sits in lines such as C/I Load Control, Common Expenses and Energy Select that have no matching program page in the DSM report. The DSM report still reconciles to the ECCR exhibit program by program for the 14 programs it covers.
4. **Participation sensitivity.** Under the stated assumption that 30% of each program's cost is fixed, 80% participation raises $/kWh by {eccr.scenario(1, 1, 0.8)[0] / 0.8 - 1:.1%} and 120% changes it by {eccr.scenario(1, 1, 1.2)[0] / 1.2 - 1:.1%} (outputs/participation_sensitivity.csv). Fixed-cost shares were not available in the filings, so this is illustrative.

## Recommendation
Treat this as a screening list, not a finding: request program-level cost detail and measure lives for the highest-$/kWh programs above, and ask Tampa Electric to reconcile its summary to its program pages before relying on either number.
"""
(ROOT / "docs").mkdir(exist_ok=True)
(ROOT / "docs" / "memo.md").write_text(memo)
