import csv, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import eccr  # noqa: E402

progs = eccr.load_programs()
out = ROOT / "outputs"; out.mkdir(exist_ok=True)

# 1. program metrics
rows = []
for p in progs:
    a = eccr.analyzable(p)
    r = {"utility": p["utility"], "program": p["program"], "cost_basis": eccr.cost_basis(p["utility"]),
         "program_cost_usd": p["cost"],
         "annual_kwh_at_meter": p["kwh"], "demand_program": p["demand_program"],
         "cost_per_kwh_usd": eccr.cost_per_kwh(p["cost"], p["kwh"]) if a else None}
    for v in eccr.AVOIDED_COST_SCENARIOS:
        r[f"payback_years_at_{v:.2f}_per_kwh"] = eccr.payback_years(p["cost"], p["kwh"], v) if a else None
    rows.append(r)
with open(out / "program_metrics.csv", "w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=list(rows[0])); w.writeheader()
    for r in rows:
        w.writerow({k: (round(v, 4) if isinstance(v, float) else v) for k, v in r.items()})

# 2. participation sensitivity
srows = []
for p in progs:
    if not eccr.analyzable(p):
        continue
    for s in eccr.PARTICIPATION_SCENARIOS:
        c, k = eccr.scenario(p["cost"], p["kwh"], s)
        srows.append({"utility": p["utility"], "program": p["program"], "participation_share": s,
                      "cost_usd": round(c), "annual_kwh": round(k), "cost_per_kwh_usd": round(c / k, 4)})
with open(out / "participation_sensitivity.csv", "w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=list(srows[0])); w.writeheader(); w.writerows(srows)

# 3. reconciliation checks
tot = eccr.utility_totals(progs)
goals = {r["utility"]: r for r in csv.DictReader(open(ROOT / "data" / "goals_vs_achieved_2025.csv"))}
eccr_rows = list(csv.DictReader(open(ROOT / "data" / "eccr_2025_costs.csv")))
ct2 = {r["utility"]: r for r in csv.DictReader(open(ROOT / "data" / "ct2_totals_2025.csv"))}
mapping = list(csv.DictReader(open(ROOT / "data" / "dsm_to_eccr_map.csv")))
TOL_PER_PROGRAM = {"Tampa Electric": 50}  # TECO's DSM report rounds to $0.1k; others to $1k
UTILS = ("Florida Power & Light", "Duke Energy Florida", "Tampa Electric")

lines = ["# Reconciliation checks (generated by scripts/analyze.py)", ""]
lines.append("## Savings: sum of program pages vs. utility-reported total (GWh at generator)")
lines.append("| Utility | Sum of program pages | Reported total | Difference |\n|---|---|---|---|")
for u in UTILS + ("Florida Public Utilities",):
    s_ = tot[u]["kwh_gen"] / 1e6; rep = float(goals[u]["achieved_gwh"])
    lines.append(f"| {u} | {s_:.3f} | {rep:.3f} | {s_ - rep:+.3f} ({(s_ - rep) / rep:+.1%}) |")
fp = tot["Florida Public Utilities"]
lines += ["", "**FPUC meter/generator labels.** FPUC's program pages sum to "
          f"{fp['kwh_meter'] / 1e6:.3f} GWh at the meter and {fp['kwh_gen'] / 1e6:.3f} GWh at the generator. "
          "Its summary prints 0.127 GWh in Table 2-3 (labelled 'At the Generator') and 0.131 GWh in Table 2-6 "
          "('At the Meter'): the energy totals appear swapped. Generator savings should exceed meter savings, "
          "and the winter MW totals in the same tables are labelled correctly.", ""]

summary = {}
for u in UTILS:
    rows_u = [r for r in eccr_rows if r["utility"] == u]
    line_sum = sum(int(r["total_cost_usd"]) for r in rows_u)
    t = int(ct2[u]["ct2_total_usd"])
    lines += [f"## {u}: ECCR true-up (Schedule CT-2/CT-3, 2025)",
              f"- {len(rows_u)} cost lines sum to ${line_sum:,}; filed total ${t:,} ({ct2[u]['what']}); "
              f"difference ${line_sum - t:,}.", ""]
    dsm = {p["program"]: p for p in progs if p["utility"] == u}
    m_u = [m for m in mapping if m["utility"] == u]
    groups = {}
    for m in m_u:
        groups.setdefault(m["eccr_program"], []).append(m["dsm_program"])
    ex_by = {r["eccr_program"]: int(r["total_cost_usd"]) for r in rows_u}
    tol = TOL_PER_PROGRAM.get(u, 500)
    lines.append("| ECCR line | DSM report program(s) | DSM report $ | ECCR $ | Difference | Within rounding |")
    lines.append("|---|---|---|---|---|---|")
    n_ok = n_bad = 0
    for ename, dnames in groups.items():
        d = sum(dsm[n]["cost"] for n in dnames)
        if not ename:
            lines.append(f"| (none) | {'; '.join(dnames)} | {d:,.0f} | - | - | DSM page only |")
            continue
        e = ex_by[ename]
        ok = abs(d - e) <= tol * len(dnames)
        n_ok += ok; n_bad += not ok
        lines.append(f"| {ename} | {'; '.join(dnames)} | {d:,.0f} | {e:,} | {d - e:+,.0f} | {'yes' if ok else 'NO'} |")
    missing = [n for n in dsm if n not in {m["dsm_program"] for m in m_u}]
    for n in missing:
        lines.append(f"| (unmapped) | {n} | {dsm[n]['cost']:,.0f} | - | - | NOT MAPPED |")
    extra = [(r["eccr_program"], int(r["total_cost_usd"])) for r in rows_u if r["eccr_program"] not in groups]
    extra_total = sum(v for _, v in extra)
    lines += ["", f"ECCR lines with no DSM program page (recovered through the clause but not reported as programs):"]
    lines += [f"- {n}: ${v:,}" for n, v in extra]
    lines += [f"- **Total: ${extra_total:,} ({extra_total / t:.1%} of filed total)**", ""]
    summary[u] = {"matched": n_ok, "mismatched": n_bad, "extra_total": extra_total, "extra_share": extra_total / t,
                  "extra": extra, "ct2_total": t, "unmapped": missing}

lines += ["## Florida Public Utilities: costs",
          "FPUC's report (Table 4-1) gives direct program costs only, $"
          f"{sum(p['cost'] for p in progs if p['utility'] == 'Florida Public Utilities'):,.0f} in total for 2025, and says "
          "they are 'actual 2025 direct costs to each program sub-ledger'. FPUC's ECCR true-up was not located in the "
          "filings reviewed, so these costs are not cross-checked and are not comparable to the other utilities' "
          "fully loaded program costs.", ""]
(out / "checks.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))

# 4. staff-style memo (numbers generated from the data, not typed by hand)
ap = [p for p in progs if eccr.rankable(p)]
fpuc = [p for p in progs if p["utility"] == "Florida Public Utilities" and eccr.analyzable(p)]
mat = sorted([p for p in ap if p["cost"] >= 100_000], key=lambda p: p["cost"] / p["kwh"])
name = lambda p: p["program"].title() if p["program"].isupper() else p["program"]
fmt = lambda p: f"| {p['utility']} | {name(p)} | ${p['cost']:,.0f} | {p['kwh'] / 1e6:,.2f} | ${p['cost'] / p['kwh']:.2f} | {eccr.payback_years(p['cost'], p['kwh'], 0.10):.1f} |"
hdr = "| Utility | Program | 2025 cost | GWh saved (meter, first-year) | $ per kWh | Years at $0.10/kWh |\n|---|---|---|---|---|---|"
a_cost = sum(p["cost"] for p in ap); a_kwh = sum(p["kwh"] for p in ap)
n_util = len({p["utility"] for p in progs})
cost_lines = "\n".join(
    f"- **{u}**: {s_['matched']} of {s_['matched'] + s_['mismatched']} DSM-to-ECCR cost comparisons agree within rounding; "
    f"${s_['extra_total'] / 1e6:,.1f} million ({s_['extra_share']:.0%} of the filed total) is in ECCR lines with no DSM program page "
    f"(largest: {max(s_['extra'], key=lambda x: x[1])[0]}, ${max(s_['extra'], key=lambda x: x[1])[1] / 1e6:,.1f} million)."
    for u, s_ in summary.items())
bad_lines = [l for l in lines if l.startswith("| ") and l.rstrip().endswith("| NO |")]
n_cmp = sum(v["matched"] + v["mismatched"] for v in summary.values())
n_bad = sum(v["mismatched"] for v in summary.values())
if n_bad:
    det = "; ".join(f"{l.split('|')[1].strip()} (DSM report ${abs(int(l.split('|')[5].strip().replace(',', ''))):,} below the ECCR exhibit)" for l in bad_lines)
    cost_match_sentence = (f"{n_cmp - n_bad} of {n_cmp} DSM-report program costs match the ECCR exhibits within the report's rounding. "
                           f"The exceptions are small: {det}, both Tampa Electric programs with large capital-investment "
                           "(depreciation and return) amounts in the true-up.")
else:
    cost_match_sentence = f"All {n_cmp} DSM-report program costs match the ECCR exhibits within the report's rounding."
fpuc_lines = "\n".join(f"| {name(p)} | ${p['cost']:,.0f} | {p['kwh']:,.0f} | ${p['cost'] / p['kwh']:.2f} |" for p in fpuc)
memo = f"""# Memo: Screening of 2025 Conservation Program Cost-Effectiveness (Florida investor-owned electric utilities)

*Independent portfolio analysis built from public filings; not an official Commission staff product. Method and limits: docs/METHODOLOGY.md.*

## Purpose
Screen the energy-saving programs Florida's four investor-owned electric utilities reported for 2025, check the reported costs against each utility's Energy Conservation Cost Recovery (ECCR) final true-up filing, and identify which programs warrant a closer look.

## Scope of what was analyzed
- {len(progs)} programs from {n_util} utilities' 2025 DSM annual reports. {len(ap)} energy-efficiency programs from FPL, Duke and Tampa Electric have both cost and credited kWh and are ranked below. Demand-response/load-control programs (credited in kW) and programs with no kWh credited can't be ranked on cost per kWh.
- FPL, Duke and Tampa Electric program costs were cross-checked line by line against their 2025 ECCR true-up exhibits (Docket 20260002-EG).
- The {len(ap)} ranked programs cost ${a_cost / 1e6:,.1f} million and credit {a_kwh / 1e6:,.1f} GWh of first-year savings at the meter, an average of ${a_cost / a_kwh:.3f} per kWh.
- Florida Public Utilities reports direct costs only, so its programs are shown separately rather than ranked with the others.

## Lowest cost per kWh saved (programs costing at least $100,000)
{hdr}
""" + "\n".join(fmt(p) for p in mat[:6]) + f"""

## Highest cost per kWh saved (programs costing at least $100,000)
{hdr}
""" + "\n".join(fmt(p) for p in mat[-6:][::-1]) + f"""

## Florida Public Utilities (direct costs only; not comparable to the tables above)
| Program | 2025 direct cost | kWh saved (meter) | $ per kWh |
|---|---|---|---|
{fpuc_lines}

FPUC's three commercial programs had no participants in 2025.

## Goals comparison (2025, as reported by each utility)
""" + "\n".join(f"- {u}: {r['achieved_gwh']} GWh achieved vs. {r['goal_gwh']} GWh goal ({r['basis']})." for u, r in goals.items()) + f"""

## Cost cross-check against ECCR filings
{cost_lines}

## Observations for follow-up
1. **Ranking is sensitive to what a program's cost includes.** Audit and education programs carry cost but credit little direct savings, so their $/kWh looks poor by construction. They should be judged on what they feed into other programs, which these filings do not show.
2. **Program costs reconcile closely; savings totals do not always.** {cost_match_sentence} On savings, Tampa Electric's program pages sum to {tot['Tampa Electric']['kwh_gen'] / 1e6:.1f} GWh at the generator against 65.8 GWh in its summary (a gap of {abs(tot['Tampa Electric']['kwh_gen'] / 1e6 - 65.8):.1f} GWh), and FPUC's summary appears to swap its meter and generator energy totals (0.127 vs. 0.131 GWh). FPL's reconcile exactly and Duke's within rounding. See outputs/checks.md.
3. **Costs recovered outside the reported programs.** Each utility's ECCR true-up includes material costs in lines with no program page in its DSM report: a program closed to new participants (FPL's Commercial/Industrial Load Control, the largest single item), common and administrative expenses, research and development, cogeneration and qualifying-facility administration, pilots and a regulatory asset (amounts above). Because these costs don't appear in the program-level reporting, a reviewer should confirm each is supported and properly recoverable through the clause.
4. **Participation sensitivity.** Under the stated assumption that 30% of each program's cost is fixed, 80% participation raises $/kWh by {eccr.scenario(1, 1, 0.8)[0] / 0.8 - 1:.1%} and 120% changes it by {eccr.scenario(1, 1, 1.2)[0] / 1.2 - 1:.1%} (outputs/participation_sensitivity.csv). Fixed-cost shares were not available in the filings, so this is illustrative.

## Recommendation
Treat this as a screening list, not a finding. Request measure lives and cost detail for the highest-$/kWh programs above; ask Tampa Electric to reconcile its summary savings to its program pages and FPUC to correct its Table 2-3/2-6 labels; and request support for the ECCR lines that have no corresponding DSM program page.
"""
(ROOT / "docs").mkdir(exist_ok=True)
(ROOT / "docs" / "memo.md").write_text(memo)
